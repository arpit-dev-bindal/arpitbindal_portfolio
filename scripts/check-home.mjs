import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const output = 'design/phase-6/review';
await mkdir(output, { recursive: true });
const report = { checks: [], errors: [] };
try {
 const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
 page.on('pageerror', error => report.errors.push(error.message));
 await page.goto('http://127.0.0.1:4175/');
 await page.locator('.visitor-scene').waitFor();
 await page.evaluate(() => document.fonts.ready);
 await page.screenshot({ path: `${output}/desktop-home.png`, fullPage: true });
 assert.equal(await page.locator('#ai-next').evaluate(el => el.compareDocumentPosition(document.querySelector('#journey')) & Node.DOCUMENT_POSITION_FOLLOWING), 4);
 for (const slug of ['backupdata', 'lighthouse', '1mb', 'turby']) assert.ok(await page.locator(`main a[href="/work/${slug}"]`).count());
 assert.equal(await page.locator('canvas').count(), 0);
 assert.equal(await page.locator('video').getAttribute('src'), null);
 assert.equal(await page.locator('[data-home-reveal]').evaluateAll(nodes => nodes.every(el => getComputedStyle(el).transform === 'none')), true);
 report.checks.push('Home links all four studies; AI precedes career; reduced motion keeps text visible and media deferred');
 await page.emulateMedia({ reducedMotion: 'no-preference' });
 await page.locator('.scene-widget[data-ready="true"]').waitFor();
 await page.getByRole('link', { name: 'View my work', exact: false }).click();
 await page.waitForTimeout(800);
 assert.equal(await page.locator('#work h2').isVisible(), true);
 await page.locator('#film-root').scrollIntoViewIfNeeded();
 await page.locator('.scroll-film[data-ready="true"]').waitFor();
 await page.locator('.visitor-film-controls summary').click();
 await page.getByRole('button', { name: 'Use scroll' }).click();
 await page.waitForTimeout(200);
 const range = await page.locator('.scroll-film').evaluate(el => ({ top: el.getBoundingClientRect().top + scrollY - innerHeight * .8, length: el.getBoundingClientRect().height + innerHeight * .6 }));
 for (const progress of [.2, .8, .3]) {
   await page.evaluate(y => scrollTo({ top: y, behavior: 'instant' }), range.top + range.length * progress);
   await page.waitForTimeout(1000);
   const actual = await page.locator('video').evaluate(video => video.currentTime / video.duration);
   assert.ok(Math.abs(actual - progress) < .1, `Film expected ${progress}, received ${actual}`);
 }
 report.checks.push('The main work link works; the Home film follows forward and reverse scroll');
 await page.getByRole('button', { name: 'Motion: on' }).click();
 await page.waitForFunction(() => !document.querySelector('canvas'));
 assert.equal(await page.locator('[data-home-reveal]').evaluateAll(nodes => nodes.every(el => getComputedStyle(el).transform === 'none')), true);
 assert.equal(await page.locator('video').evaluate(video => video.paused), true);
 report.checks.push('Motion off removes reveal transforms, stops the scene, and pauses video');
 const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
 await mobile.goto('http://127.0.0.1:4175/');
 await mobile.getByRole('button', { name: 'Enable 3D' }).waitFor();
 await mobile.evaluate(() => document.fonts.ready);
 await mobile.screenshot({ path: `${output}/mobile-home.png`, fullPage: true });
 assert.equal(await mobile.locator('canvas').count(), 0);
 assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
 const plain = await browser.newPage({ javaScriptEnabled: false, viewport: { width: 320, height: 900 } });
 await plain.goto('http://127.0.0.1:4175/');
 assert.equal(await plain.locator('.home-project').count(), 3);
 assert.equal(await plain.locator('#scene-root img').evaluate(img => img.complete && img.naturalWidth > 0), true);
 assert.equal(await plain.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
 report.checks.push('Mobile starts with a poster; the 320px page retains projects and images without JavaScript');
 assert.deepEqual(report.errors, []);
 console.log(`Passed ${report.checks.length} Home check groups.`);
} finally { await writeFile(`${output}/browser-checks.json`, JSON.stringify(report, null, 2)); await browser.close(); }
