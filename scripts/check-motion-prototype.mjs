import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const output = resolve('design/phase-3/review');
await mkdir(output, { recursive: true });
const report = { checks: [], desktop: {}, mobile: {}, errors: [] };
const base = 'http://127.0.0.1:4174';
const ready = page => page.locator('.scene-widget[data-ready="true"]').waitFor({ timeout: 20000 });
const diag = page => page.evaluate(() => ({ ...window.portfolioPrototype.diagnostics }));
const capture = (page, file) => page.screenshot({ path: `${output}/${file}.png` });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => report.errors.push(error.message));
  await page.goto(base); await ready(page);
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(800);
  await capture(page, 'desktop-scene');
  const restA = await diag(page); await page.waitForTimeout(300); const restB = await diag(page);
  assert.ok(restB.frames - restA.frames <= 2, 'Scene must stop after it settles');
  assert.ok(restB.calls <= 80 && restB.triangles <= 100000);
  report.checks.push('Desktop scene loads within draw and triangle budgets; demand rendering rests');
  await page.getByRole('button', { name: 'Systems', exact: true }).focus(); await page.keyboard.press('Enter');
  await page.waitForFunction(() => Math.abs(window.portfolioPrototype.diagnostics.lift[1] - .38) < .01);
  assert.equal((await diag(page)).owner, 'manual');
  await page.getByRole('button', { name: 'Assemble', exact: true }).click();
  await page.waitForFunction(() => window.portfolioPrototype.diagnostics.spread < .01);
  report.checks.push('Keyboard layer selection and Assemble change the actual model pose');
  const story = await page.evaluate(() => window.portfolioPrototype.triggers().find(trigger => trigger.id === 'portfolio-story'));
  assert.ok(story && story.end - story.start <= 1201);
  await page.evaluate(y => scrollTo({ top: y, behavior: 'instant' }), story.start + (story.end - story.start) * .5);
  await page.waitForTimeout(800);
  assert.equal((await diag(page)).owner, 'manual');
  assert.ok((await diag(page)).spread < .01);
  await page.getByRole('button', { name: 'Resume scroll', exact: true }).click();
  await page.waitForFunction(() => window.portfolioPrototype.diagnostics.spread > .9);
  report.checks.push('Manual control overrides scroll until Resume scroll; pin distance stays within 120vh');
  await page.getByRole('button', { name: 'Skip to work', exact: true }).click();
  assert.equal(await page.evaluate(() => document.activeElement?.textContent), 'Work with a wider scope.');
  await page.locator('#film-root').scrollIntoViewIfNeeded();
  await page.locator('.scroll-film[data-ready="true"]').waitFor();
  await page.waitForFunction(() => window.portfolioPrototype.triggers().some(trigger => trigger.id === 'portfolio-film'));
  const film = await page.evaluate(() => window.portfolioPrototype.triggers().find(trigger => trigger.id === 'portfolio-film'));
  for (const fraction of [.2, .8, .3]) {
    await page.evaluate(y => scrollTo({ top: y, behavior: 'instant' }), film.start + (film.end - film.start) * fraction);
    await page.waitForFunction(time => { const media = document.querySelector('video'); return !media.seeking && Math.abs(media.currentTime - time) < .15; }, fraction * 6);
  }
  const held = await page.locator('video').evaluate(media => media.currentTime);
  await page.waitForTimeout(350);
  assert.ok(Math.abs(await page.locator('video').evaluate(media => media.currentTime) - held) < .05);
  assert.equal((await diag(page)).active, false);
  await capture(page, 'desktop-film');
  report.checks.push('Film follows forward and reverse scroll, holds when stopped, and pauses the scene');
  await page.getByRole('button', { name: 'Play film', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('video').paused);
  assert.equal(await page.locator('.scroll-film').getAttribute('data-mode'), 'play');
  assert.ok(!(await page.evaluate(() => window.portfolioPrototype.triggers())).some(trigger => trigger.id === 'portfolio-film'));
  await page.getByRole('button', { name: 'Pause film', exact: true }).click();
  await page.getByRole('button', { name: 'Use scroll', exact: true }).click();
  await page.waitForFunction(() => window.portfolioPrototype.triggers().some(trigger => trigger.id === 'portfolio-film'));
  report.checks.push('Manual playback removes scroll control; Use scroll restores it');
  await page.getByRole('button', { name: 'Skip film', exact: true }).click();
  assert.match(await page.evaluate(() => document.activeElement?.textContent), /Context connects/);
  await page.getByRole('button', { name: 'Motion: on', exact: true }).first().click();
  await page.waitForFunction(() => window.portfolioPrototype.triggers().length === 0);
  assert.equal(await page.locator('canvas').count(), 0);
  assert.equal(await page.locator('video').evaluate(media => media.paused), true);
  report.checks.push('Global motion off removes pinning, canvas, and automatic video');
  await page.getByRole('button', { name: 'Motion: off', exact: true }).first().click();
  await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' })); await ready(page);
  for (let cycle = 0; cycle < 3; cycle++) {
    await page.evaluate(() => window.portfolioPrototype.unmountScene());
    await page.waitForFunction(() => !window.portfolioPrototype.triggers().some(trigger => trigger.id === 'portfolio-story'));
    assert.equal(await page.locator('canvas').count(), 0);
    await page.evaluate(() => window.portfolioPrototype.mountScene()); await ready(page);
    assert.equal(await page.locator('canvas').count(), 1);
  }
  report.checks.push('Three unmount and remount cycles leave one canvas and one story trigger');
  await page.evaluate(() => document.querySelector('canvas').dispatchEvent(new Event('webglcontextlost', { cancelable: true })));
  await page.getByText('3D is unavailable. The still image remains available.').waitFor();
  assert.equal(await page.locator('canvas').count(), 0);
  report.checks.push('Context loss restores the poster');
  report.desktop = await diag(page);
  await page.close();

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  mobile.on('pageerror', error => report.errors.push(error.message));
  await mobile.goto(base); await mobile.getByRole('button', { name: 'Enable 3D' }).waitFor();
  assert.equal(await mobile.locator('canvas').count(), 0);
  assert.ok(!(await mobile.evaluate(() => window.portfolioPrototype.triggers())).some(trigger => trigger.id === 'portfolio-story'));
  assert.equal(await mobile.locator('video').getAttribute('src'), null);
  await capture(mobile, 'mobile-poster');
  await mobile.getByRole('button', { name: 'Enable 3D' }).tap(); await ready(mobile);
  await mobile.getByRole('button', { name: 'Intelligence', exact: true }).tap();
  await mobile.waitForFunction(() => window.portfolioPrototype.diagnostics.lift[3] > .37);
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await capture(mobile, 'mobile-scene');
  report.mobile = await diag(mobile);
  assert.equal(report.mobile.tier, 'light');
  report.checks.push('Mobile starts with a poster, defers video, avoids pinning, and supports touch selection');
  await mobile.close();

  const reduced = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const requests = []; reduced.on('request', request => requests.push(request.url()));
  await reduced.goto(base); await reduced.getByText('Motion is off. Layer buttons still show each description.').waitFor();
  assert.equal(await reduced.locator('canvas').count(), 0);
  assert.equal(await reduced.locator('video').getAttribute('src'), null);
  assert.equal(requests.some(url => /SceneCanvas|\.mp4/.test(url)), false);
  await reduced.getByRole('button', { name: 'Systems', exact: true }).click();
  await reduced.getByText('Backend, SDKs, and infrastructure.', { exact: true }).first().waitFor();
  await reduced.emulateMedia({ reducedMotion: 'no-preference' }); await ready(reduced);
  await reduced.emulateMedia({ reducedMotion: 'reduce' }); await reduced.waitForFunction(() => !document.querySelector('canvas'));
  report.checks.push('Reduced motion defers 3D and video; live preference changes clean up the scene');
  await reduced.close();
  const blocked = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await blocked.addInitScript(() => {
    const getContext = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function(type, ...args) { return /webgl/i.test(type) ? null : getContext.call(this, type, ...args); };
  });
  await blocked.route('**/media/material-film.mp4', route => route.abort());
  await blocked.goto(base);
  await blocked.getByText('3D is unavailable. The still image remains available.').waitFor();
  await blocked.locator('#film-root').scrollIntoViewIfNeeded();
  await blocked.getByText('The film is unavailable. The still image remains available.').waitFor();
  assert.equal(await blocked.locator('.scene-poster').evaluate(image => image.complete && image.naturalWidth > 0), true);
  report.checks.push('Blocked WebGL and failed video requests retain posters and readable content');
  await blocked.close();
  const noScript = await browser.newPage({ javaScriptEnabled: false, viewport: { width: 390, height: 844 } });
  await noScript.goto(base);
  assert.match(await noScript.locator('h1').textContent(), /I build complete/);
  assert.equal(await noScript.getByRole('link', { name: 'View my work' }).getAttribute('href'), '#work');
  assert.equal(await noScript.locator('canvas').count(), 0);
  report.checks.push('Without JavaScript, the main text, work link, poster, and native video remain available');
  await noScript.close();
  for (const width of [360, 768, 1024]) {
    const layout = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    await layout.goto(base); await layout.locator('.scene-widget').waitFor();
    assert.equal(await layout.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Overflow at ${width}`);
    await layout.close();
  }
  report.checks.push('Additional 360, 768, and 1024px layouts have no horizontal overflow');
  assert.deepEqual(report.errors, []);
  console.log(`Passed ${report.checks.length} motion checks.`);
} finally {
  await writeFile(`${output}/browser-checks.json`, JSON.stringify(report, null, 2));
  await browser.close();
}
